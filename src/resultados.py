"""Part 5 - business questions. Runs sql/q1..q6 against the marts and writes the results, in Spanish.

    results/YYYY/RESULTS_MM.md  one file per month of MES (YYYY = its year, MM = its month): MES against
                           the same month of the previous year, month against month, with the quality and
                           quarantine section, the six questions, their interpretations and the
                           conclusions. `make all MES=2025-02` writes results/2025/RESULTS_02.md (February
                           2025 vs February 2024) and `make all MES=2026-02` writes results/2026/RESULTS_02.md
                           (February 2026 vs February 2025), in local mode (INGEST_MODE=direct
                           WAREHOUSE=duckdb) and in cloud mode alike. A rerun of the same MES replaces its file.
    README.md              the tables and interpretations of the last run, between the RESULTADOS markers.

Each question is one SQL file. ${YEAR}, ${MONTH} and ${CMP_YEAR} are filled from --mes. The
interpretations are not static text: src/interpretacion.py writes them from the results of this run,
the context queries of sql/contexto/ and the schema and quality reports (what each Parquet file
brought, what was converted and what went to quarantine and why).

Every figure is backed by a Superset chart (src/evidencia.py): each block of the report ends with links to
the charts that show its figures, the answers of q1..q6 are reconciled with the evidence tables
(marts.ev_*) that those charts read, and every number of the text is looked up in the charts its block
cites. A month that cannot be compared (its data or the data of the year before is missing) gets a report
that says so, without figures or conclusions, and never replaces a report that has them.

    python -m src.resultados --mes 2025-01      # one month
    python -m src.resultados --anio 2025        # every month of 2025 that can be compared with what is loaded
"""

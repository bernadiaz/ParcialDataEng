"""Part 5 - business questions. Runs sql/q1..q6 against the marts and writes RESULTADOS.md.

Each question is one SQL file. ${YEAR}, ${MONTH} and ${CMP_YEAR} are filled from --mes. The
interpretations (q1..q6 and the closing conclusiones) come from sql/interpretations.yaml. The same
tables and interpretations are also written into README.md, between the RESULTADOS markers, so the
README never drifts from the last run.

    python -m src.resultados --mes 2025-01
"""
from __future__ import annotations

import argparse
import sys
from datetime import datetime, timezone
from decimal import Decimal
from pathlib import Path
from string import Template
from typing import Any

import duckdb
import yaml

from src.config import ROOT, RUN_ID, SQL_DIR, Month, Settings, get_logger, track_step

log = get_logger("resultados")
OUTPUT = ROOT / "RESULTADOS.md"


def question_files() -> list[Path]:
    files = sorted(SQL_DIR.glob("q[1-9]_*.sql"))
    if len(files) != 6:
        raise RuntimeError(f"expected 6 question files in {SQL_DIR}, found {len(files)}")
    return files


def render_sql(path: Path, month: Month) -> str:
    params = {"YEAR": month.year, "MONTH": month.month, "CMP_YEAR": month.comparison.year}
    return Template(path.read_text(encoding="utf-8")).substitute(params).strip().rstrip(";")


def title_of(path: Path) -> str:
    first = path.read_text(encoding="utf-8").splitlines()[0]
    return first.removeprefix("--").strip()


def run_query(settings: Settings, sql: str, connection: Any) -> tuple[list[str], list[tuple]]:
    if settings.warehouse == "duckdb":
        cursor = connection.execute(sql)
        return [d[0] for d in cursor.description], cursor.fetchall()
    with connection.cursor() as cur:
        cur.execute(sql)
        return [d[0].lower() for d in cur.description], cur.fetchall()


CODE_COLUMNS = {"year", "month", "pickup_hour", "payment_type", "pu_location_id", "do_location_id"}


def fmt(value: Any, column: str = "") -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return str(value).lower()
    if column in CODE_COLUMNS:  # codes, not quantities: no thousands separator
        return str(int(value)) if isinstance(value, (int, float, Decimal)) else str(value)
    if isinstance(value, int):
        return f"{value:,}"
    if isinstance(value, Decimal) and value == value.to_integral_value():
        return f"{int(value):,}"
    if isinstance(value, (float, Decimal)):
        return f"{value:,.2f}"
    return str(value)


def markdown_table(columns: list[str], rows: list[tuple]) -> str:
    header = "| " + " | ".join(columns) + " |"
    divider = "|" + "|".join("---" for _ in columns) + "|"
    body = ["| " + " | ".join(fmt(v, c) for v, c in zip(row, columns)) + " |" for row in rows]
    return "\n".join([header, divider, *body])


PENDING = "_Pending: write the interpretation in sql/interpretations.yaml._"
README = ROOT / "README.md"
README_START = "<!-- RESULTADOS:START - generated by `make questions` from sql/q*.sql and sql/interpretations.yaml; do not edit by hand -->"
README_END = "<!-- RESULTADOS:END -->"


def note_markdown(text: str | None, label: str = "Interpretación") -> str:
    """One paragraph stays inline; several lines (q6, conclusiones) become a bullet list."""
    lines = [line.strip() for line in (text or "").strip().splitlines() if line.strip()]
    if not lines:
        return f"**{label}:** {PENDING}"
    if len(lines) == 1:
        return f"**{label}:** {lines[0]}"
    return "\n".join([f"**{label}:**", "", *[f"- {line}" for line in lines]])


def collect(settings: Settings, month: Month, connection: Any) -> list[dict[str, Any]]:
    """Runs q1..q6 and pairs each result with its interpretation."""
    interpretations = load_interpretations()
    results = []
    for index, path in enumerate(question_files(), start=1):
        columns, rows = run_query(settings, render_sql(path, month), connection)
        results.append({
            "index": index,
            "path": path,
            "title": title_of(path).split(":", 1)[-1].strip(),
            "table": markdown_table(columns, rows),
            "note": interpretations.get(f"q{index}"),
        })
        log.info("q%d %s: %d rows", index, path.stem, len(rows))
    return results


def load_interpretations() -> dict[str, Any]:
    return yaml.safe_load((SQL_DIR / "interpretations.yaml").read_text(encoding="utf-8")) or {}


def conclusions_markdown(heading: str) -> list[str]:
    text = (load_interpretations().get("conclusiones") or "").strip()
    if not text:
        return []
    return [heading, "", *[f"- {line.strip()}" for line in text.splitlines() if line.strip()], ""]


def build(settings: Settings, month: Month, connection: Any, results: list[dict[str, Any]] | None = None) -> str:
    results = results if results is not None else collect(settings, month, connection)
    engine = "Snowflake" if settings.warehouse == "snowflake" else "DuckDB (offline validation target)"
    parts = [
        "# RESULTADOS",
        "",
        f"Assigned month **{month.label}** compared with **{month.comparison.label}**. "
        f"Queries run on the dbt marts in {engine}. Interpretations are in Spanish (`sql/interpretations.yaml`).",
        f"Generated by `make questions MES={month.label}` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC (run `{RUN_ID}`).",
        "",
    ]
    for r in results:
        parts += [
            f"## {r['index']}. {r['title']}",
            "",
            f"Query: [`sql/{r['path'].name}`](sql/{r['path'].name})",
            "",
            "```sql",
            r["path"].read_text(encoding="utf-8").strip(),
            "```",
            "",
            r["table"],
            "",
            note_markdown(r["note"]),
            "",
        ]
    parts += conclusions_markdown("## Conclusiones")
    return "\n".join(parts)


def readme_block(settings: Settings, month: Month, results: list[dict[str, Any]]) -> str:
    """The results section of README.md: tables and interpretations, without the SQL."""
    engine = "Snowflake" if settings.warehouse == "snowflake" else "DuckDB (offline validation target)"
    parts = [
        README_START,
        "",
        f"Assigned month **{month.label}** vs **{month.comparison.label}**, from the dbt marts in {engine} "
        f"(run `{RUN_ID}`, {datetime.now(timezone.utc):%Y-%m-%d}). The queries are in [RESULTADOS.md](RESULTADOS.md). "
        "The interpretations are in Spanish and come from `sql/interpretations.yaml`.",
        "",
    ]
    for r in results:
        parts += [f"#### Q{r['index']}. {r['title']}", "", r["table"], "", note_markdown(r["note"]), ""]
    parts += conclusions_markdown("#### Conclusiones")
    parts.append(README_END)
    return "\n".join(parts)


def replace_block(text: str, block: str) -> str | None:
    """Swaps the generated block between the README markers; None when the markers are missing."""
    start, end = text.find(README_START), text.find(README_END)
    if start < 0 or end < start:
        return None
    return text[:start] + block + text[end + len(README_END):]


def open_connection(settings: Settings) -> Any:
    if settings.warehouse == "duckdb":
        return duckdb.connect(str(settings.warehouse_db), read_only=True)
    from src.load_snowflake import snowflake_connect

    return snowflake_connect(step="questions")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--mes", required=True, help="assigned month YYYY-MM")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args(argv)
    settings = Settings.from_env()
    with track_step(settings, "questions", args.mes):
        write_results(settings, Month.parse(args.mes), args.output)
    return 0


def write_results(settings: Settings, month: Month, output: Path = OUTPUT, readme: Path | None = README) -> Path:
    connection = open_connection(settings)
    try:
        results = collect(settings, month, connection)
    finally:
        connection.close()
    output.write_text(build(settings, month, None, results), encoding="utf-8")
    log.info("wrote %s", output)
    if readme is not None and readme.exists():
        updated = replace_block(readme.read_text(encoding="utf-8"), readme_block(settings, month, results))
        if updated is None:
            log.warning("%s has no results markers: README not updated", readme.name)
        else:
            readme.write_text(updated, encoding="utf-8")
            log.info("updated the results section of %s", readme.name)
    return output


if __name__ == "__main__":
    sys.exit(main())
